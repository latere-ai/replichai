// DeleteDataset removes one dataset row; a row that is not there is ErrNotFound.
func (s *FSStore) DeleteDataset(_ context.Context, id string) error {
	root, err := s.open()
	if err != nil {
		return err
	}
	defer func() { _ = root.Close() }()
	if err := root.Remove(datasetName(id)); err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return ErrNotFound
		}
		return fmt.Errorf("delete dataset: %w", err)
	}
	return nil
}

// FSArtifactStore holds bytes under a directory, one file per key. Keys may
// contain slashes and become nested directories.
type FSArtifactStore struct {
	root string
}

// NewFSArtifactStore builds a filesystem artifact store rooted at dir.
func NewFSArtifactStore(dir string) (*FSArtifactStore, error) {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, fmt.Errorf("create artifact dir: %w", err)
	}
	return &FSArtifactStore{root: dir}, nil
}

// keyName turns a key into the slash-separated name it has inside the store,
// refusing any key that would escape it. Keys are generated internally, but a
// store must never write outside its root, and a caller that asks for such a
// key receives an error rather than a silently clamped path.
func (a *FSArtifactStore) keyName(key string) (string, error) {
	clean, err := relpath.Clean(filepath.ToSlash(key))
	if err != nil || clean == "." {
		return "", fmt.Errorf("artifact key escapes the store: %q", key)
	}
	return clean, nil
}

// open pins the store directory as a confined root, so every operation below is
// resolved by the operating system against that open directory. This prevents
// a symlink inside the store, for example one from a reproduction's own
// committed tree, from redirecting a write or a delete outside it, which
// keyName alone cannot rule out.
func (a *FSArtifactStore) open() (*os.Root, error) {
	root, err := os.OpenRoot(a.root)
	if err != nil {
		return nil, fmt.Errorf("open artifact store: %w", err)
	}
	return root, nil
}

// Put stores content under key and returns its checksum.
func (a *FSArtifactStore) Put(_ context.Context, key string, content []byte) (string, error) {
	name, err := a.keyName(key)
	if err != nil {
		return "", err
	}
	root, err := a.open()
	if err != nil {
		return "", err
	}
	defer func() { _ = root.Close() }()
	if dir := path.Dir(name); dir != "." {
		if err := root.MkdirAll(dir, 0o755); err != nil {
			return "", fmt.Errorf("create artifact parent: %w", err)
		}
	}
	if err := root.WriteFile(name, content, 0o644); err != nil {
		return "", fmt.Errorf("write artifact: %w", err)
	}
	return Checksum(content), nil
}

// Get reads the content stored under key, reporting false when there is none.
func (a *FSArtifactStore) Get(_ context.Context, key string) ([]byte, bool, error) {
	name, err := a.keyName(key)
	if err != nil {
		return nil, false, err
	}
	root, err := a.open()
	if err != nil {
		return nil, false, err
	}
	defer func() { _ = root.Close() }()
	content, err := root.ReadFile(name)
	if errors.Is(err, os.ErrNotExist) {
		return nil, false, nil
	}
	if err != nil {
		return nil, false, fmt.Errorf("read artifact: %w", err)
	}
	return content, true, nil
}

// Delete removes the content stored under key; removing a key that is not there
// is a no-op.
func (a *FSArtifactStore) Delete(_ context.Context, key string) error {
	name, err := a.keyName(key)
	if err != nil {
		return err
	}
	root, err := a.open()
	if err != nil {
		return err
	}
	defer func() { _ = root.Close() }()
	if err := root.Remove(name); err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("delete artifact: %w", err)
	}
	return nil
}

// DeletePrefix removes every stored key beginning with prefix; this is how a
// dataset deletion reaches an experiment's derived artifacts. It walks the tree
// rather than removing a directory, so a prefix that is not a directory
// boundary still deletes exactly the matching keys.
func (a *FSArtifactStore) DeletePrefix(_ context.Context, prefix string) error {
	root, err := a.open()
	if err != nil {
		return err
	}
	defer func() { _ = root.Close() }()
	// Walking the root's own fs.FS yields slash-separated names relative to the
	// store, which is the form a key already has, and removing through the root
	// removes the entry the walk named rather than whatever the path resolves to
	// a moment later.
	return fs.WalkDir(root.FS(), ".", func(name string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() || !strings.HasPrefix(name, prefix) {
			return nil
		}
		if err := root.Remove(name); err != nil {
			return fmt.Errorf("delete artifact: %w", err)
		}
		return nil
	})
}

func writeJSON(root *os.Root, name string, v any) error {
	raw, err := json.Marshal(v, wirejson.Stored, wirejson.Embedding, jsontext.WithIndent("  "))
	if err != nil {
		return err
	}
	if err := root.WriteFile(name, raw, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", path.Base(name), err)
	}
	return nil
}

func readJSON(root *os.Root, name string, v any) error {
	raw, err := root.ReadFile(name)
	if errors.Is(err, os.ErrNotExist) {
		return ErrNotFound
	}
	if err != nil {
		return fmt.Errorf("read %s: %w", path.Base(name), err)
	}
	return json.Unmarshal(raw, v, wirejson.Foreign)
}
