// FSStore persists rows as JSON files under a directory, so an experiment
// survives a restart before Postgres exists. One file per record; the layout is
// an implementation detail the interface hides.
type FSStore struct {
	root string
}

// NewFSStore builds a filesystem store rooted at dir, creating it if needed.
func NewFSStore(dir string) (*FSStore, error) {
	for _, sub := range []string{"experiments", "datasets"} {
		if err := os.MkdirAll(filepath.Join(dir, sub), 0o755); err != nil {
			return nil, fmt.Errorf("create store dir: %w", err)
		}
	}
	return &FSStore{root: dir}, nil
}

// open pins the store directory as a confined root. Every read, write, and
// removal below resolves against it, so a row id that climbs out, such as
// "../../x", fails with an escape error instead of naming a file elsewhere on
// disk. The confinement is the store's boundary, not the collection's: an id
// of "../datasets/x" still cleans to a name inside the store, so it names the
// wrong collection rather than being refused. Ids are generated by NewID and
// no caller passes one in from a request, but the store is the last place
// that can refuse a bad one and does not rely on its callers.
func (s *FSStore) open() (*os.Root, error) {
	root, err := os.OpenRoot(s.root)
	if err != nil {
		return nil, fmt.Errorf("open store: %w", err)
	}
	return root, nil
}

// experimentName and datasetName are a row's location relative to the store
// root; the *Path forms are the same location as an absolute path, for the
// existence probes that do not go through the root.
func experimentName(id string) string { return path.Join("experiments", id+".json") }
func datasetName(id string) string    { return path.Join("datasets", id+".json") }

func (s *FSStore) experimentPath(id string) string {
	return filepath.Join(s.root, filepath.FromSlash(experimentName(id)))
}
func (s *FSStore) datasetPath(id string) string {
	return filepath.Join(s.root, filepath.FromSlash(datasetName(id)))
}

// CreateExperiment writes a new experiment row, refusing to overwrite one that
// already exists.
func (s *FSStore) CreateExperiment(_ context.Context, e *Experiment) error {
	if e.ID == "" {
		return ErrNoID
	}
	if _, err := os.Stat(s.experimentPath(e.ID)); err == nil {
		return ErrExists
	}
	root, err := s.open()
	if err != nil {
		return err
	}
	defer func() { _ = root.Close() }()
	return writeJSON(root, experimentName(e.ID), e)
}

// GetExperiment reads one experiment row; a row that is not there is
// ErrNotFound.
func (s *FSStore) GetExperiment(_ context.Context, id string) (*Experiment, error) {
	root, err := s.open()
	if err != nil {
		return nil, err
	}
	defer func() { _ = root.Close() }()
	var e Experiment
	if err := readJSON(root, experimentName(id), &e); err != nil {
		return nil, err
	}
	return &e, nil
}

// UpdateExperiment overwrites an existing experiment row; it never creates one.
func (s *FSStore) UpdateExperiment(_ context.Context, e *Experiment) error {
	if _, err := os.Stat(s.experimentPath(e.ID)); err != nil {
		return ErrNotFound
	}
	root, err := s.open()
	if err != nil {
		return err
	}
	defer func() { _ = root.Close() }()
	return writeJSON(root, experimentName(e.ID), e)
}

// ListExperiments returns every experiment belonging to one project.
func (s *FSStore) ListExperiments(_ context.Context, projectID string) ([]*Experiment, error) {
	entries, err := os.ReadDir(filepath.Join(s.root, "experiments"))
	if err != nil {
		return nil, fmt.Errorf("list experiments: %w", err)
	}
	root, err := s.open()
	if err != nil {
		return nil, err
	}
	defer func() { _ = root.Close() }()
	var out []*Experiment
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".json") {
			continue
		}
		var e Experiment
		if err := readJSON(root, path.Join("experiments", entry.Name()), &e); err != nil {
			return nil, err
		}
		if e.ProjectID == projectID {
			ec := e
			out = append(out, &ec)
		}
	}
	return out, nil
}

